#!/usr/bin/env bash
# Writes /data/SBFspot.cfg from the add-on options.
#
# Generated rather than shipped, because the file has to contain the inverter's password and
# the broker's address: a file in the image would be a file in a public repository. It is
# rewritten at every start, so editing it by hand has no lasting effect -- the options are the
# single source of truth.
#
# Inputs are environment variables, all required except TIMEZONE:
#   BT_ADDRESS, INVERTER_PASSWORD, PLANT_NAME, MQTT_TOPIC, TIMEZONE
set -euo pipefail

readonly target="${1:?usage: generate-config.sh <target>}"

: "${BT_ADDRESS:?BT_ADDRESS is required}"
: "${INVERTER_PASSWORD:?INVERTER_PASSWORD is required}"
: "${PLANT_NAME:?PLANT_NAME is required}"
: "${MQTT_TOPIC:?MQTT_TOPIC is required}"
: "${TIMEZONE:=UTC}"

# The keys SBFspot acts on are listed here, and only those. Everything else keeps upstream's
# default, which is the point: a key written here is a decision, and a decision nobody made is
# better left to the author of the file format.
#
# The two that matter most are `CSV_Export=0` -- this add-on publishes to MQTT and writes no
# files, so there is no history to keep and nothing to fill the disk with -- and `SynchTime=0`.
#
# `SynchTime` is the one that is easy to get wrong. Its default is 1, not 0, and on a Bluetooth
# connection upstream writes the plant clock to the inverter whenever it is above zero
# (`Inverter.cpp`: `if (ConnectionType == CT_BLUETOOTH && synchTime > 0) SetPlantTime_V2(...)`),
# which happens on *every* poll -- not only when `-settime` is passed. Without this line the
# add-on writes to the inverter once a minute while claiming to be read-only. Nothing here
# writes anything to the inverter.
cat > "${target}" <<EOF
# Generated by the SBFspot MQTT bridge add-on at every start. Do not edit: it is overwritten.
BTAddress=${BT_ADDRESS}
Password=${INVERTER_PASSWORD}
Plantname=${PLANT_NAME}
MIS_Enabled=0
BTConnectRetries=10
SynchTime=0
Timezone=${TIMEZONE}
Locale=en-US
DateTimeFormat=%Y-%m-%dT%H:%M:%S
DateFormat=%Y-%m-%d
TimeFormat=%H:%M:%S
DecimalPoint=dot
CSV_Export=0
OutputPath=/data/smadata/%Y
OutputPathEvents=/data/smadata/%Y/Events
MQTT_Publisher=/usr/bin/sbfspot-mqtt/publish.sh
# The double quotes are not decoration: SBFspot rewrites them as single quotes on Linux, and
# they are what keeps the JSON in one argument.
MQTT_PublisherArgs=-m "{{message}}"
MQTT_Topic=${MQTT_TOPIC}
MQTT_ItemFormat="{key}": {value}
MQTT_ItemDelimiter=comma
MQTT_Data=Timestamp,Plantname,InvSerial,InvName,InvTime,InvStatus,InvTemperature,InvGridRelay,InvClass,InvType,InvSwVer,EToday,ETotal,PACTot,PDC,IDC,UDC,GridFreq,OperTm,FeedTm
EOF

# It holds the inverter's password.
chmod 600 "${target}"
